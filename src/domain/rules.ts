export const DEFAULT_RULE_SET: RuleSetId = "ai_allowed";

export function ruleSetOf(settings: { ruleSet?: string } | null | undefined): RuleSet {
  const id = settings?.ruleSet as RuleSetId | undefined;
  return (id && RULE_SETS[id]) || RULE_SETS[DEFAULT_RULE_SET];
}
