/**
 * Tournament rule sets (COMP-1). A round picks one; it decides whether AI may
 * run once the round is live and whether recording is possible, and the round
 * shows its reminder. Sources: docs/research/speech-strategy.md §0 (NSDA device
 * guidelines 2023–24, UIL CX manual, OSDA resources, NSDA AI rule).
 */

export type AiPolicy = "allowed" | "prep_only" | "off";
export type RuleSetId = "ai_allowed" | "nsda" | "uil" | "ohio" | "tournament_allows" | "practice";

export interface RuleSet {
  id: RuleSetId;
  label: string;
  /** what the AI may do: allowed = also during the live round; prep_only = before the round only */
  aiPolicy: AiPolicy;
  /** recording opponents: only with everyone's consent, or not at all */
  recording: "consent" | "off";
  reminder: string;
}

